"""Format-2 network manifests, written by the code before guard PR-3 (main at 86176838), still replay.

``golden/network_manifests_format_2.json`` was generated by that code over one network: a solve citing a hidden solve and
a solve citing a reference to nothing, selected under the exploratory and the curated profile. The recorded entry is
``reference_solve_ref`` null with ``reference_withheld`` true wherever the reference was unavailable (hidden under curated,
or naming nothing under either profile), and the evidence verdict recorded with it is "unavailable". Replay must keep
reading that flag for a manifest of the previous format: dropping it re-answers the recorded evidence as "declared".
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest

from app.services.network_selection import ReplayError, replay_network
from app.services.network_selection.manifest import replay_matches, replay_network_assessment

GOLDEN = json.loads((Path(__file__).parent / "golden" / "network_manifests_format_2.json").read_text(encoding="utf-8"))
PROFILES = ["exploratory", "curated"]


def entries(manifest):
    return {s["solve_ref"]: s["validation"]["entries"][0] for s in manifest["solves"] if s["validation"]}


def test_the_premise_the_fixture_holds_the_three_shapes():
    assert all(GOLDEN[p]["manifest_format_version"] == 2 for p in PROFILES)
    exploratory, curated = entries(GOLDEN["exploratory"]), entries(GOLDEN["curated"])
    shown = [e for e in exploratory.values() if e["reference_solve_ref"] is not None]
    assert [e["reference_solve_ref"] for e in shown] == [GOLDEN["hidden_solve_ref"]]  # exploratory names the solve
    assert len([e for e in exploratory.values() if e.get("reference_withheld")]) == 1  # the reference to nothing
    assert all(e["reference_solve_ref"] is None and e["reference_withheld"] is True for e in curated.values())
    assert GOLDEN["hidden_solve_ref"] not in json.dumps(GOLDEN["curated"])


@pytest.mark.parametrize("profile", PROFILES)
def test_a_format_2_manifest_replays_after_the_upgrade(profile):
    manifest = copy.deepcopy(GOLDEN[profile])
    assert replay_matches(manifest)
    replay_network(manifest)
    assert replay_network_assessment(manifest)


def test_the_withheld_flag_still_decides_the_recorded_evidence_of_a_format_2_manifest():
    """Kills: ``stated = {... if not entry.get("reference_withheld")}`` dropped from the assessment.

    The recorded verdict for a withheld reference is ``unavailable``; without the flag replay re-answers ``declared``."""
    manifest = copy.deepcopy(GOLDEN["curated"])
    assert all(a["evidence"]["model_fidelity"] == "unavailable" for a in manifest["assessments"]["determinations"])
    for entry in entries(manifest).values():
        entry["reference_withheld"] = False  # the same facts without the flag: the evidence would now count
    with pytest.raises((ReplayError, ValueError)):
        replay_network_assessment(manifest)
